import { mailConfigured } from "./mail.js";
import { rateLimit } from "./http.js";
import type { Env } from "./types.js";

export type ApprovalKind = "transfer" | "merge";
export type ApprovalIntent = "accept" | "decline";

/** A link is a capability for exactly one request, recipient and decision. */
export async function approvalSignature(
  env: Env,
  approval: {
    targetAccountId: string;
    kind: ApprovalKind;
    requestId: string;
    intent: ApprovalIntent;
    email: string;
  },
): Promise<string> {
  const key = await crypto.subtle.importKey(
    "raw",
    new TextEncoder().encode(env.BETTER_AUTH_SECRET),
    { name: "HMAC", hash: "SHA-256" },
    false,
    ["sign"],
  );
  const message = JSON.stringify([
    "approval-v1",
    approval.kind,
    approval.requestId,
    approval.intent,
    approval.targetAccountId,
    approval.email.toLowerCase(),
  ]);
  const signature = await crypto.subtle.sign(
    "HMAC",
    key,
    new TextEncoder().encode(message),
  );
  return Array.from(new Uint8Array(signature), (byte) =>
    byte.toString(16).padStart(2, "0"),
  ).join("");
}

/**
 * A notification is best effort: the request remains available in the account
 * portal if delivery fails or the recipient has no verified email address.
 * Links authorize only the decision and request for the verified recipient.
 */
export async function sendApprovalMail(
  env: Env,
  approval: { targetAccountId: string; kind: ApprovalKind; requestId: string },
  now: number,
  fetcher: typeof fetch = fetch,
): Promise<"sent" | "unavailable"> {
  try {
    if (!mailConfigured(env)) return "unavailable";
    // Restrict links to the UUIDs generated by our request creators.
    if (
      !/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(
        approval.requestId,
      )
    )
      return "unavailable";
    const recipient = await env.DB.prepare(
      'SELECT email, "emailVerified" AS verified FROM "user" WHERE id = ?',
    )
      .bind(approval.targetAccountId)
      .first<{ email: string; verified: number | boolean }>();
    if (!recipient?.verified || !recipient.email) return "unavailable";

    // In addition to creator limits, protect each recipient and the mail quota.
    const targetLimit = await rateLimit(
      env.DB,
      `approval-mail:target:${approval.targetAccountId}`,
      10,
      3600,
      now,
    );
    if (!targetLimit.allowed) return "unavailable";
    const globalLimit = await rateLimit(
      env.DB,
      "approval-mail:global",
      250,
      86400,
      now,
    );
    if (!globalLimit.allowed) return "unavailable";

    const link = async (intent: ApprovalIntent) => {
      const url = new URL("/email-approval", env.AUTH_ORIGIN);
      url.searchParams.set("kind", approval.kind);
      url.searchParams.set("id", approval.requestId);
      url.searchParams.set("intent", intent);
      url.searchParams.set(
        "token",
        await approvalSignature(env, {
          ...approval,
          intent,
          email: recipient.email,
        }),
      );
      return url.toString();
    };
    const [acceptLink, declineLink] = await Promise.all([
      link("accept"),
      link("decline"),
    ]);
    const operation =
      approval.kind === "merge" ? "sloučení účtů" : "převod profilu";
    const response = await fetcher("https://api.brevo.com/v3/smtp/email", {
      method: "POST",
      headers: {
        "api-key": env.BREVO_API_KEY!,
        "content-type": "application/json",
        accept: "application/json",
      },
      redirect: "manual",
      signal: AbortSignal.timeout(12_000),
      body: JSON.stringify({
        sender: { email: env.MAIL_FROM, name: "StreamerAI" },
        to: [{ email: recipient.email }],
        subject: "StreamerAI — žádost ke schválení",
        textContent: `Čeká na vás žádost o ${operation}.\n\nPřijmout:\n${acceptLink}\n\nZamítnout:\n${declineLink}\n\nOdkazy fungují bez přihlášení a platí 24 hodin. Přijetí může vyžadovat výběr profilů. Nikomu odkazy nepřeposílejte. Pokud žádost neočekáváte, můžete ji zamítnout.`,
      }),
    });
    await response.body?.cancel();
    return response.ok ? "sent" : "unavailable";
  } catch {
    // Do not expose account details, provider responses, or mail contents.
    return "unavailable";
  }
}
